package com.example;

public class Diem {
    private final double x; // hoành độ
    private final double y; // tung độ

    public Diem(double x, double y) {
        this.x = x;
        this.y = y;
    }

    public double getX() {
        return x;
    }

    public double getY() {
        return y;
    }
}
